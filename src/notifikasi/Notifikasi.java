    private void tabelNotifikasiMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelNotifikasiMouseClicked
        // TODO add your handling code here:
        int baris = tabelNotifikasi.getSelectedRow();

        selectedId = tabelNotifikasi.getValueAt(baris, 0).toString();
        txtIdTugas.setText(tabelNotifikasi.getValueAt(baris, 1).toString());
        txtPesan.setText(tabelNotifikasi.getValueAt(baris, 2).toString());

        try {
            String tanggal = tabelNotifikasi.getValueAt(baris, 3).toString();
            SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd HH:mm:ss");
            Date dt = sdf.parse(tanggal);
            dateNotifikasi.setDate(dt);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Tanggal gagal ditampilkan");
        }

        cmbStatus.setSelectedItem(tabelNotifikasi.getValueAt(baris, 4).toString());

        btnSimpan.setEnabled(false);
        btnEdit.setEnabled(true);
        btnHapus.setEnabled(true);
    }//GEN-LAST:event_tabelNotifikasiMouseClicked

    private void btnCariTugasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCariTugasActionPerformed
        // TODO add your handling code here:
        try {
            if (txtIdTugas.getText().trim().equals("")) {
                JOptionPane.showMessageDialog(null, "ID Tugas harus diisi dulu");
                return;
            }
            Connection conn = Koneksi.getConnection();
            String sql = "SELECT * FROM tb_tugas WHERE id_tugas=?";
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, txtIdTugas.getText());
            ResultSet rs = pst.executeQuery();
            if (rs.next()) {
                txtJudulTugas.setText(rs.getString("judul_tugas"));
            } else {
                JOptionPane.showMessageDialog(null, "ID Tugas tidak ditemukan");
                txtJudulTugas.setText("");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error : " + e.getMessage());
        }
    }//GEN-LAST:event_btnCariTugasActionPerformed

