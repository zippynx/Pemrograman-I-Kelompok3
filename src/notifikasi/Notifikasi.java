    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // TODO add your handling code here:
        // VALIDASI
        if (txtIdTugas.getText().trim().isEmpty()
                || txtPesan.getText().trim().isEmpty()
                || dateNotifikasi.getDate() == null) {

            JOptionPane.showMessageDialog(null,
                    "Semua field wajib harus diisi!",
                    "Peringatan",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            Connection conn = Koneksi.getConnection();

            String sql = "INSERT INTO tb_notifikasi "
                    + "(id_tugas, pesan_notifikasi, tanggal_notifikasi, status_notifikasi) "
                    + "VALUES (?, ?, ?, ?)";

            PreparedStatement pst = conn.prepareStatement(sql);

            pst.setString(1, txtIdTugas.getText());
            pst.setString(2, txtPesan.getText());

            SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd HH:mm:ss");
            String tanggal = sdf.format(dateNotifikasi.getDate());
            pst.setString(3, tanggal);

            pst.setString(4, cmbStatus.getSelectedItem().toString());

            pst.executeUpdate();

            JOptionPane.showMessageDialog(null,
                    "Data Berhasil Disimpan!",
                    "Sukses",
                    JOptionPane.INFORMATION_MESSAGE);

            bersihkanForm();
            tampilData();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null,
                    "Data Gagal Disimpan: " + e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        // TODO add your handling code here:

        if (selectedId.equals("")) {
            JOptionPane.showMessageDialog(null,
                    "Pilih data yang akan dihapus terlebih dahulu");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(null,
                "Yakin mau hapus data ini?");

        if (confirm == 0) {
            try {
                Connection conn = Koneksi.getConnection();
                String sql = "DELETE FROM tb_notifikasi WHERE id_notifikasi=?";
                PreparedStatement pst = conn.prepareStatement(sql);
                pst.setString(1, selectedId);
                pst.executeUpdate();

                JOptionPane.showMessageDialog(null, "Data Berhasil Dihapus!");

                bersihkanForm();
                tampilData();
                btnSimpan.setEnabled(true);
                btnEdit.setEnabled(false);
                btnHapus.setEnabled(false);

            } catch (Exception e) {
                JOptionPane.showMessageDialog(null,
                        "Gagal Hapus: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnHapusActionPerformed

