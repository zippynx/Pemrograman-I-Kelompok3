    private void tampilData() {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("ID");
        model.addColumn("ID Tugas");
        model.addColumn("Pesan");
        model.addColumn("Tanggal Notifikasi");
        model.addColumn("Status");

        try {
            Connection conn = Koneksi.getConnection();
            String sql = "SELECT * FROM tb_notifikasi";
            Statement st = conn.createStatement();
            ResultSet rs = st.executeQuery(sql);

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("id_notifikasi"),
                    rs.getString("id_tugas"),
                    rs.getString("pesan_notifikasi"),
                    rs.getString("tanggal_notifikasi"),
                    rs.getString("status_notifikasi")
                });
            }
            tabelNotifikasi.setModel(model);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null,
                    "Gagal Menampilkan Data: " + e.getMessage());
        }
    }

