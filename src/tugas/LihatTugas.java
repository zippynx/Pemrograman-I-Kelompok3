    private void tampilData() {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("ID");
        model.addColumn("ID Mahasiswa");
        model.addColumn("ID Matakuliah");
        model.addColumn("Judul Tugas");
        model.addColumn("Deskripsi");
        model.addColumn("Tanggal Dibuat");
        model.addColumn("Deadline");
        model.addColumn("Status");

        try {
            Connection conn = Koneksi.getConnection();
            String sql = "SELECT * FROM tb_tugas";
            Statement st = conn.createStatement();
            ResultSet rs = st.executeQuery(sql);

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("id_tugas"),
                    rs.getString("id_mahasiswa"),
                    rs.getString("id_matakuliah"),
                    rs.getString("judul_tugas"),
                    rs.getString("deskripsi_tugas"),
                    rs.getString("tanggal_dibuat"),
                    rs.getString("deadline"),
                    rs.getString("status_tugas")
                });
            }
            tabelLihatTugas.setModel(model);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null,
                    "Gagal Menampilkan Data: " + e.getMessage());
        }
    }

