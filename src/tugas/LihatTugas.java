    private void btnCariActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCariActionPerformed
        // TODO add your handling code here:
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("ID");
        model.addColumn("ID Mahasiswa");
        model.addColumn("ID Matakuliah");
        model.addColumn("Judul Tugas");
        model.addColumn("Deskripsi");
        model.addColumn("Tanggal Dibuat");
        model.addColumn("Deadline");
        model.addColumn("Status");

        try {
            Connection conn = Koneksi.getConnection();

            String keyword = txtCari.getText();

            String sql = "SELECT * FROM tb_tugas WHERE "
                    + "id_tugas LIKE ? OR "
                    + "judul_tugas LIKE ? OR "
                    + "deskripsi_tugas LIKE ? OR "
                    + "tanggal_dibuat LIKE ? OR "
                    + "deadline LIKE ? OR "
                    + "status_tugas LIKE ?";

            PreparedStatement pst = conn.prepareStatement(sql);

            for (int i = 1; i <= 6; i++) {
                pst.setString(i, "%" + keyword + "%");
            }

            ResultSet rs = pst.executeQuery();

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("id_tugas"),
                    rs.getString("id_mahasiswa"),
                    rs.getString("id_matakuliah"),
                    rs.getString("judul_tugas"),
                    rs.getString("deskripsi_tugas"),
                    rs.getString("tanggal_dibuat"),
                    rs.getString("deadline"),
                    rs.getString("status_tugas")
                });
            }
            tabelLihatTugas.setModel(model);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null,
                    "Gagal Mencari Data: " + e.getMessage());
        }
    }//GEN-LAST:event_btnCariActionPerformed

    private void btnPrintActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPrintActionPerformed
        // TODO add your handling code here:
        try {
            // Buat file HTML
            File file = new File("data_tugas.html");
            FileWriter fw = new FileWriter(file);

            // Tulis HTML
            fw.write("<html><head><title>Data Tugas</title></head><body>");
            fw.write("<h2>Daftar Tugas</h2>");
            fw.write("<table border='1' cellpadding='5' cellspacing='0'>");

            // Header tabel
            fw.write("<tr>"
                    + "<th>ID</th>"
                    + "<th>ID Mahasiswa</th>"
                    + "<th>ID Matakuliah</th>"
                    + "<th>Judul Tugas</th>"
                    + "<th>Deskripsi</th>"
                    + "<th>Tanggal Dibuat</th>"
                    + "<th>Deadline</th>"
                    + "<th>Status</th>"
                    + "</tr>");

            // Isi data dari tabel
            for (int i = 0; i < tabelLihatTugas.getRowCount(); i++) {
                fw.write("<tr>"
                        + "<td>" + tabelLihatTugas.getValueAt(i, 0) + "</td>"
                        + "<td>" + tabelLihatTugas.getValueAt(i, 1) + "</td>"
                        + "<td>" + tabelLihatTugas.getValueAt(i, 2) + "</td>"
                        + "<td>" + tabelLihatTugas.getValueAt(i, 3) + "</td>"
                        + "<td>" + tabelLihatTugas.getValueAt(i, 4) + "</td>"
                        + "<td>" + tabelLihatTugas.getValueAt(i, 5) + "</td>"
                        + "<td>" + tabelLihatTugas.getValueAt(i, 6) + "</td>"
                        + "<td>" + tabelLihatTugas.getValueAt(i, 7) + "</td>"
                        + "</tr>");
            }

            fw.write("</table></body></html>");
            fw.close();

            // Buka di browser
            Desktop.getDesktop().browse(file.toURI());

            JOptionPane.showMessageDialog(null,
                    "Data Berhasil Diekspor!",
                    "Sukses",
                    JOptionPane.INFORMATION_MESSAGE);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null,
                    "Gagal Export: " + e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnPrintActionPerformed

