    private void tampilData() {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("ID Tugas");
        model.addColumn("ID Mahasiswa");
        model.addColumn("ID Matakuliah");
        model.addColumn("Judul Tugas");
        model.addColumn("Deskripsi");
        model.addColumn("Tanggal Dibuat");
        model.addColumn("Deadline");
        model.addColumn("Status");
        try {
            Connection conn = Koneksi.getConnection();
            String sql = "SELECT * FROM tb_tugas";
            Statement st = conn.createStatement();
            ResultSet rs = st.executeQuery(sql);
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("id_tugas"),
                    rs.getString("id_mahasiswa"),
                    rs.getString("id_matakuliah"),
                    rs.getString("judul_tugas"),
                    rs.getString("deskripsi_tugas"),
                    rs.getString("tanggal_dibuat"),
                    rs.getString("deadline"),
                    rs.getString("status_tugas")
                });
            }
            tabelTugas.setModel(model);
            warnaStatus();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null,
                    "Gagal Menampilkan Data : " + e.getMessage());
        }
    }
    
    private void warnaStatus() {
    tabelTugas.setDefaultRenderer(Object.class,
            new javax.swing.table.DefaultTableCellRenderer() {
        @Override
        public java.awt.Component getTableCellRendererComponent(
                javax.swing.JTable table,
                Object value,
                boolean isSelected,
                boolean hasFocus,
                int row,
                int column) {
            java.awt.Component c =
                    super.getTableCellRendererComponent(
                            table, value, isSelected, hasFocus, row, column);
            String status = table.getValueAt(row, 7).toString();
            if (!isSelected) {
                if (status.equals("belum selesai")) {
                    c.setBackground(java.awt.Color.PINK);
                } else if (status.equals("proses")) {
                    c.setBackground(java.awt.Color.YELLOW);
                } else if (status.equals("selesai")) {
                    c.setBackground(java.awt.Color.GREEN);
                } else {
                    c.setBackground(java.awt.Color.WHITE);
                }
            }
            return c;
        }
    });
}

