    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // TODO add your handling code here:
        // VALIDASI
        try {
            if (txtIdMahasiswa.getText().trim().equals("")) {
                JOptionPane.showMessageDialog(null, "ID Mahasiswa harus diisi");
                return;
            }
            if (txtIdMatkul.getText().trim().equals("")) {
                JOptionPane.showMessageDialog(null, "ID Matakuliah harus diisi");
                return;
            }
            if (txtJudul.getText().trim().equals("")) {
                JOptionPane.showMessageDialog(null, "Judul tugas harus diisi");
                return;
            }
            if (dateDibuat.getDate() == null) {
                JOptionPane.showMessageDialog(null, "Tanggal dibuat harus diisi");
                return;
            }
            if (dateDeadline.getDate() == null) {
                JOptionPane.showMessageDialog(null, "Deadline harus diisi");
                return;
            }
            Connection conn = Koneksi.getConnection();
            String sql = "INSERT INTO tb_tugas "
                    + "(id_mahasiswa, id_matakuliah, judul_tugas, "
                    + "deskripsi_tugas, tanggal_dibuat, deadline, status_tugas) "
                    + "VALUES (?, ?, ?, ?, ?, ?, ?)";
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, txtIdMahasiswa.getText());
            pst.setString(2, txtIdMatkul.getText());
            pst.setString(3, txtJudul.getText());
            pst.setString(4, txtDeskripsi.getText());
            SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
            pst.setString(5, sdf.format(dateDibuat.getDate()));
            pst.setString(6, sdf.format(dateDeadline.getDate()));
            pst.setString(7, cmbStatus.getSelectedItem().toString());
            pst.executeUpdate();
            JOptionPane.showMessageDialog(null, "Data berhasil disimpan");
            tampilData();
            // Reset form
            txtIdMahasiswa.setText("");
            txtIdMatkul.setText("");
            txtJudul.setText("");
            txtDeskripsi.setText("");
            dateDibuat.setDate(null);
            dateDeadline.setDate(null);
            cmbStatus.setSelectedIndex(0);
            idTugas = "";
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Gagal menyimpan : " + e.getMessage());
        }
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        // TODO add your handling code here:
        try {
            if (idTugas.equals("")) {
                JOptionPane.showMessageDialog(null, "Pilih data terlebih dahulu");
                return;
            }
            int konfirmasi = JOptionPane.showConfirmDialog(null,
                    "Yakin ingin menghapus data ini?",
                    "Konfirmasi Hapus",
                    JOptionPane.YES_NO_OPTION);
            if (konfirmasi == JOptionPane.YES_OPTION) {
                Connection conn = Koneksi.getConnection();
                String sql = "DELETE FROM tb_tugas WHERE id_tugas=?";
                PreparedStatement pst = conn.prepareStatement(sql);
                pst.setString(1, idTugas);
                pst.executeUpdate();
                JOptionPane.showMessageDialog(null, "Data berhasil dihapus");
                tampilData();
                txtIdMahasiswa.setText("");
                txtIdMatkul.setText("");
                txtJudul.setText("");
                txtDeskripsi.setText("");
                dateDibuat.setDate(null);
                dateDeadline.setDate(null);
                cmbStatus.setSelectedIndex(0);
                idTugas = "";
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Gagal menghapus : " + e.getMessage());
        }
    }//GEN-LAST:event_btnHapusActionPerformed

