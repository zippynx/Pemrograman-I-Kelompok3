    private void tampilData() {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("ID");
        model.addColumn("Kode Matkul");
        model.addColumn("Nama Matakuliah");
        model.addColumn("Nama Dosen");
        model.addColumn("SKS");

        try {
            Connection conn = Koneksi.getConnection();
            String sql = "SELECT * FROM tb_matakuliah";
            Statement st = conn.createStatement();
            ResultSet rs = st.executeQuery(sql);

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("id_matakuliah"),
                    rs.getString("kode_matkul"),
                    rs.getString("nama_matakuliah"),
                    rs.getString("nama_dosen"),
                    rs.getString("sks")
                });
            }
            tabelMatkul.setModel(model);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null,
                    "Gagal Menampilkan Data: " + e.getMessage());
        }
    }

