    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // TODO add your handling code here:
        try {
            Connection conn = Koneksi.getConnection();
            String sql = "INSERT INTO tb_matakuliah "
                    + "(kode_matkul, nama_matakuliah, nama_dosen, sks) "
                    + "VALUES (?, ?, ?, ?)";
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, txtKode.getText());
            pst.setString(2, txtNamaMatkul.getText());
            pst.setString(3, txtDosen.getText());
            pst.setString(4, txtSKS.getText());
            pst.executeUpdate();

            JOptionPane.showMessageDialog(null, "Data Berhasil Disimpan!");
            bersihkanForm();
            tampilData();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null,
                    "Gagal Simpan: " + e.getMessage());
        }
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        // TODO add your handling code here:
        int confirm = JOptionPane.showConfirmDialog(null,
                "Yakin mau hapus data ini?");
        if (confirm == 0) {
            try {
                Connection conn = Koneksi.getConnection();
                String sql = "DELETE FROM tb_matakuliah "
                        + "WHERE id_matakuliah=?";
                PreparedStatement pst = conn.prepareStatement(sql);
                pst.setString(1, selectedId);
                pst.executeUpdate();

                JOptionPane.showMessageDialog(null,
                        "Data Berhasil Dihapus!");
                bersihkanForm();
                tampilData();
                btnSimpan.setEnabled(true);
                btnEdit.setEnabled(false);
                btnHapus.setEnabled(false);

            } catch (Exception e) {
                JOptionPane.showMessageDialog(null,
                        "Gagal Hapus: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnHapusActionPerformed

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        // TODO add your handling code here:
        try {
            Connection conn = Koneksi.getConnection();
            String sql = "UPDATE tb_matakuliah SET "
                    + "kode_matkul=?, "
                    + "nama_matakuliah=?, "
                    + "nama_dosen=?, "
                    + "sks=? "
                    + "WHERE id_matakuliah=?";
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, txtKode.getText());
            pst.setString(2, txtNamaMatkul.getText());
            pst.setString(3, txtDosen.getText());
            pst.setString(4, txtSKS.getText());
            pst.setString(5, selectedId);
            pst.executeUpdate();

            JOptionPane.showMessageDialog(null, "Data Berhasil Diupdate!");
            bersihkanForm();
            tampilData();
            btnSimpan.setEnabled(true);
            btnEdit.setEnabled(false);
            btnHapus.setEnabled(false);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null,
                    "Gagal Update: " + e.getMessage());
        }
    }//GEN-LAST:event_btnEditActionPerformed

